"""動作確認用のダミー回答 CSV を作る(実際の回答ではありません)。 python make_sample_data.py"""
import numpy as np
import pandas as pd

CHORES = ["勤務表・シフト作成", "申し送り・引き継ぎ", "記録・書類作成", "物品・在庫管理", "当番・担当の割り振り",
          "院内連絡・会議の調整", "研修・勉強会の運営管理", "患者・家族への説明資料づくり", "機器の点検・保守記録", "請求・算定の確認"]
ROLES = ["看護師", "診療放射線技師", "臨床検査技師", "薬剤師", "理学療法士・作業療法士・言語聴覚士", "医療事務"]
rng = np.random.default_rng(1)
n = 120
rows = []
for _ in range(n):
    role = rng.choice(ROLES, p=[.3, .2, .12, .13, .15, .1])
    r = {"職種": role, "経験年数": rng.choice(["1年未満", "1〜3年", "4〜10年", "11〜20年", "21年以上"]),
         "勤務先の施設種別": rng.choice(["大学病院・大病院", "中小病院", "クリニック", "介護・福祉施設"]),
         "役職・購入の決裁(購入の決定権)": rng.choice(["自分で購入を決められる", "上長の承認が必要", "施設の予算で決まる", "決定には関われない"], p=[.2, .4, .25, .15])}
    base = rng.normal(0, .5)
    for i, c in enumerate(CHORES):
        w = {0: 1.2, 2: 1.0, 1: .6}.get(i, 0)  # 勤務表・記録・申し送りを負担大にしておく
        b = int(np.clip(round(2.6 + w + base + rng.normal(0, .9)), 1, 5))
        d = int(np.clip(round(b - .6 + rng.normal(0, .9)), 1, 5))
        r[f"【負担度】負担が大きいものは？ [{c}]"] = b
        r[f"【解決意欲】お金を払ってでも楽にしたいものは？ [{c}]"] = d
    r["現場で困っていること(雑務・無駄な作業)"] = rng.choice(
        ["勤務表づくりに毎月3時間かかる", "記録の二重入力がつらい", "申し送りが口頭で抜け漏れる", "紙の台帳を探す時間が無駄", ""])
    r["あったらいいソフト・道具"] = rng.choice(["勤務表の自動作成", "申し送りの共有アプリ", "在庫のバーコード管理", ""])
    mid = rng.lognormal(np.log(2500), .5)
    a, b2, c2, d2 = sorted(mid * np.array([.35, .7, 1.5, 2.6]) * rng.uniform(.85, 1.15, 4))
    r["月額いくらから安すぎて品質が不安ですか(円)"], r["月額いくらなら安いと感じますか(円)"] = round(a, -2), round(b2, -2)
    r["月額いくらから高いと感じ始めますか(円)"], r["月額いくらから高すぎて買わないですか(円)"] = round(c2, -2), round(d2, -2)
    r["購入意向: 雑務を解決するソフトがあれば購入したいですか"] = rng.choice(
        ["ぜひ購入したい", "条件次第で購入したい", "無料なら使う", "購入しない"], p=[.15, .35, .35, .15])
    r["支払う人: 費用は誰が負担しますか"] = rng.choice(["自分(個人)", "施設・部署", "分からない"], p=[.3, .45, .25])
    r["希望する形(提供形態)"] = ", ".join(rng.choice(["パソコンのソフト", "スマホアプリ", "ブラウザ(Web)", "Excelテンプレート"], size=2, replace=False))
    rows.append(r)
pd.DataFrame(rows).to_csv("sample_responses.csv", index=False, encoding="utf-8-sig")
print("sample_responses.csv を作成しました(ダミーデータ)")
